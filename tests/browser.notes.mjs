// Use only the isolated fixture server on port 8792.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {join} from 'node:path';
const {chromium} = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({channel: process.env.TICKETS_BROWSER || 'msedge', headless: true});
const context = await browser.newContext({viewport: {width: 1536, height: 960}});
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = 'http://127.0.0.1:8792';
const graph = async () => (await page.request.get(base + '/api/graph')).json();
const wait = async (fn, label) => {
  const deadline = Date.now() + 15000;
  while (!await fn()) { if (Date.now() > deadline) throw new Error(`Timed out: ${label}`); await page.waitForTimeout(80); }
};
let saves = 0;
page.on('request', request => { if (request.method() === 'PUT' && request.url().includes('/api/notes/')) saves++; });
try {
  await page.goto(base + '/graph?note=n-single-operator');
  const title = page.locator('#note-form input[name=title]');
  const abstractZh = page.locator('#note-form textarea[name=abstract_zh]');
  const abstractEn = page.locator('#note-form textarea[name=abstract_en]');
  await title.waitFor({state: 'visible'});
  await wait(async () => await page.locator('#dag .edge.relation-option').count() === 2, 'typed layout');
  assert.equal(await page.locator('#dag .edge.relation-assumes').count(), 1);
  assert.equal(await page.locator('#dag .edge.relation-supports').count(), 1);
  const styles = await page.locator('#dag .edge:not(.removed) .edge-path').evaluateAll(paths => [...new Set(paths.map(p => `${getComputedStyle(p).strokeDasharray}/${getComputedStyle(p).strokeWidth}`))]);
  assert.equal(styles.length, 5, 'all relation types have distinct stroke styles');
  assert.ok((await page.locator('#backlinks').innerText()).includes('Two-tab conflict fixture'));
  await title.fill('Premise edited on attention change');
  const originalBody = (await graph()).notes.find(n => n.id === 'n-single-operator').body;
  await abstractZh.fill('先验证多标签页编辑的冲突处理；多人协作仍是待探索方向。');
  await abstractEn.fill('Validate conflicts across tabs before exploring multi-user collaboration.');
  await page.locator('#note-form textarea[name=body]').click();
  await page.waitForTimeout(200);
  assert.equal(saves, 0);
  await abstractZh.dispatchEvent('compositionstart');
  await page.locator('#chat-input').click();
  await page.waitForTimeout(150);
  assert.equal(saves, 0, 'Chinese composition defers an attention save');
  await abstractZh.dispatchEvent('compositionend');
  await wait(async () => (await graph()).notes.find(n => n.id === 'n-single-operator').title === 'Premise edited on attention change', 'note attention save');
  assert.equal(saves, 1);
  const summarized = (await graph()).notes.find(n => n.id === 'n-single-operator');
  assert.equal(summarized.abstract_zh, await abstractZh.inputValue());
  assert.equal(summarized.abstract_en, await abstractEn.inputValue());
  assert.equal(summarized.body, originalBody);
  assert.ok(await abstractZh.evaluate(el => el.scrollHeight <= el.clientHeight + 1), 'compact abstract expands to show its paragraph');
  await wait(async () => (await page.locator('#note-form select[name=state]').inputValue()) === 'proposed', 'changed premise needs review');
  await page.locator('#note-form select[name=state]').selectOption('adopted');
  await page.locator('#chat-input').click();
  await wait(async () => (await graph()).notes.find(n => n.id === 'n-single-operator').state === 'adopted', 'explicitly adopt current text');

  await title.fill('Browser conflict draft');
  await abstractZh.fill('浏览器保留的中文摘要：先验证冲突处理。');
  const beforeConflict = (await graph()).notes.find(n => n.id === 'n-single-operator');
  await page.request.put(base + '/api/notes/n-single-operator', {data: {fields: {title: 'Other editor title', abstract_zh: '来自其他编辑器的摘要。'}, version: beforeConflict.version}});
  await wait(() => page.locator('#note-conflict').isVisible(), 'note conflict');
  assert.equal(await title.inputValue(), 'Browser conflict draft');
  assert.equal(await abstractZh.inputValue(), '浏览器保留的中文摘要：先验证冲突处理。');
  await page.locator('#note-keep-draft').click();
  await wait(async () => (await graph()).notes.find(n => n.id === 'n-single-operator').title === 'Browser conflict draft', 'note rebase');
  assert.equal((await graph()).notes.find(n => n.id === 'n-single-operator').abstract_zh, '浏览器保留的中文摘要：先验证冲突处理。');

  await page.locator('#note-form select[name=state]').selectOption('refuted');
  await page.locator('#chat-input').click();
  await wait(async () => (await graph()).tickets.find(t => t.id === 3).review_notes.includes('n-single-operator'), 'premise review propagation');
  await page.locator('#backlinks .relation').filter({hasText: '采用假设'}).getByRole('button', {name: '打开'}).click();
  await wait(() => page.locator('#ticket-form').isVisible(), 'backlink navigation');
  assert.match(await page.locator('#premise-warning').innerText(), /复核/);

  await page.locator('#local-graph').click();
  await wait(async () => await page.locator('#dag .node[data-note]').count() < 5, 'local graph');
  assert.ok(await page.locator('#dag .node[data-note]').count() > 0);
  await page.locator('#local-depth').selectOption('2');
  await page.locator('#show-notes').uncheck();
  await wait(async () => await page.locator('#dag .node[data-note]').count() === 0, 'note visibility filter');
  const savedCount = (await graph()).notes.length;
  await page.locator('#show-notes').check();
  await page.locator('#local-graph').click();
  await wait(async () => await page.locator('#dag .node[data-note]').count() === savedCount, 'global graph');

  await page.locator('#capture-note').click();
  await title.waitFor({state: 'visible'});
  await title.fill('Independent idea fixture');
  await page.locator('#note-form select[name=kind]').selectOption('idea');
  await page.locator('#note-form textarea[name=body]').fill('This idea is a Markdown note, not a ticket.');
  await abstractZh.fill('灵感保存在独立笔记；用小实验保留不确定方向。');
  await abstractEn.fill('Preserve uncertain directions in an independent note and test them with a small experiment.');
  const ticketCount = (await graph()).tickets.length;
  await page.locator('#note-save').click();
  await wait(async () => (await graph()).notes.length === savedCount + 1, 'explicit note creation');
  assert.equal((await graph()).tickets.length, ticketCount);
  await page.locator('#note-relation-type').selectOption('option');
  await page.locator('#note-relation-target').selectOption('note:n-save-question');
  const otherNote = (await graph()).notes.find(n => n.id === 'n-save-question');
  await page.request.put(base + '/api/notes/n-save-question', {data: {version: otherNote.version, fields: {title: 'Fixture question refreshed'}}});
  await wait(async () => (await page.locator('#notes-tree').innerText()).includes('Fixture question refreshed'), 'unrelated SSE refresh');
  assert.equal(await page.locator('#note-relation-type').inputValue(), 'option', 'SSE preserves a relation choice');
  assert.equal(await page.locator('#note-relation-target').inputValue(), 'note:n-save-question', 'SSE preserves the chosen target');
  await page.locator('#note-add-relation').click();
  await page.locator('#chat-input').click();
  await wait(async () => (await graph()).notes.find(n => n.title === 'Independent idea fixture').relations.some(r => r.type === 'option'), 'typed relationship save');
  await page.reload();
  await title.waitFor({state: 'visible'});
  assert.equal(await title.inputValue(), 'Independent idea fixture');
  assert.equal(await abstractZh.inputValue(), '灵感保存在独立笔记；用小实验保留不确定方向。');
  assert.equal(await abstractEn.inputValue(), 'Preserve uncertain directions in an independent note and test them with a small experiment.');
  await page.locator('#search').fill('不确定方向');
  await wait(async () => await page.locator('#dag .node[data-note]').count() === 1, 'Chinese abstract search');
  assert.equal(await page.locator('#notes-tree .tree-note').count(), 1);
  assert.match(await page.locator('#notes-tree .note-snippet').innerText(), /不确定方向/);
  await page.locator('#search').fill('SMALL EXPERIMENT');
  await wait(async () => await page.locator('#dag .node[data-note]').count() === 1, 'English abstract search');
  await page.locator('#clear-filter').click();
  await wait(async () => await page.locator('#notes-tree .tree-note').count() === savedCount + 1, 'clear abstract search');
  assert.match(await page.locator('#chat-context').innerText(), /Independent idea fixture/);
  await page.locator('#chat-input').fill('Prepare a small review preview for the attached ticket.');
  await page.locator('#send-chat').click();
  await wait(() => page.locator('#proposal').isVisible(), 'proposal with note context');
  const changedNote = (await graph()).notes.find(n => n.title === 'Independent idea fixture');
  await page.request.put(`${base}/api/notes/${changedNote.id}`, {data: {version: changedNote.version, fields: {body: 'An external edit invalidates the old proposal.'}}});
  await wait(() => page.locator('#apply-proposal').isDisabled(), 'note edit expires proposal');
  await page.locator('#reject-proposal').click();
  await wait(async () => (await page.locator('#layout-status').innerText()) === '' && await page.locator('#dag [data-note]').count() === savedCount + 1, 'final layout');
  await page.locator('#fit').click();
  await page.screenshot({path: join(process.env.TEMP, 'tickets-notes-overview.png')});
  await page.emulateMedia({colorScheme: 'dark'});
  await page.screenshot({path: join(process.env.TEMP, 'tickets-notes-dark.png')});
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: join(process.env.TEMP, 'tickets-notes-mobile.png'), fullPage: true});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  assert.deepEqual(errors, []);
  console.log('Notes browser checks passed: bilingual abstract editing/search, English-body preservation, attention save, conflict/rebase, relation styles, backlinks, local graph, reload, dark/mobile.');
} catch (error) {
  await page.screenshot({path: join(process.env.TEMP, 'tickets-notes-failure.png'), fullPage: true});
  throw error;
} finally { await browser.close(); }
